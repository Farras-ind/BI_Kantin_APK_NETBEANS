    private void login() {
        String user = txtUsername.getText().trim();
        String pass = new String(txtPassword.getPassword());

        if (user.isEmpty() || pass.isEmpty()) {
            lblPesan.setText("Username dan password wajib diisi.");
            return;
        }

        btnLogin.setEnabled(false);
        String sql = "SELECT id, role FROM users WHERE username = ? AND password = ?";
        try (Connection c = Db.get(); PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, user);
            ps.setString(2, pass);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    lblPesan.setText("Username atau password salah.");
                    txtPassword.setText("");
                    txtPassword.requestFocus();
                    return;
                }
                int id = rs.getInt("id");
                String role = rs.getString("role");

                if ("admin".equals(role)) {
                    new FormAdmin(user).setVisible(true);
                } else {
                    new FormSiswa(id, user).setVisible(true);
                }
                dispose();
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                    "Gagal terhubung ke database.\nPastikan MySQL di XAMPP sudah menyala.\n\n"
                    + ex.getMessage(), "Error database", JOptionPane.ERROR_MESSAGE);
        } finally {
            btnLogin.setEnabled(true);
        }
    }

